def build_black(i, cue, dur_render):
    filters = []
    for li, line in enumerate(cue["lines"]):
        tf = txtfile(f"black_{i}_{li}", line)
        delay = 0.4 + li*0.7
        filters.append(
            f"drawtext=fontfile={FONT_LIGHT}:textfile='{tf}':fontcolor={WHITE}:fontsize=56:"
            f"x=(w-text_w)/2:y=(h-text_h)/2+{li*84-42}:alpha='if(lt(t,{delay}),0,1)':enable='gte(t,{delay})'"
        )
    out = f"{SEGS}/seg_{i:02d}.mp4"
    vfilter = ",".join(filters) if filters else "null"
    cmd = ["ffmpeg","-y","-hide_banner","-loglevel","error","-f","lavfi",
           "-i", f"color=c=black:s={W}x{H}:r={FPS}:d={dur_render}",
           "-vf", vfilter, "-pix_fmt","yuv420p","-r",str(FPS), out]
    run(cmd)
    return out

def build_clip(i, cue, dur_render):
    out = f"{SEGS}/seg_{i:02d}.mp4"
    run(["ffmpeg","-y","-hide_banner","-loglevel","error","-i", f"{CLIPS}/{cue['file']}",
         "-vf", f"scale={W}:{H},fps={FPS},tpad=stop_mode=clone:stop_duration=1.0", "-t", f"{dur_render:.4f}",
         "-pix_fmt","yuv420p","-r",str(FPS), out])
    return out

def build_cycle_precise(i, cue, dur_render):
    dur = cue["t1"] - cue["t0"]
    words = cue["words"]
    filters = []
    bg = cue.get("bgimg")
    if bg:
        filters.append(f"scale={W}:-2,crop={W}:{H}")
        filters.append("boxblur=10:1")
        filters.append("eq=brightness=-0.32:saturation=0.7")
    n = len(words)
    for wi, (w, wt) in enumerate(words):
        local_t = wt - cue["t0"]
        tf = txtfile(f"cyc_{i}_{wi}", w)
        xpos = f"(w*{ (wi+0.5)/n })-text_w/2"
        filters.append(
            f"drawtext=fontfile={FONT_BOLD}:textfile='{tf}':fontsize=44:"
            f"fontcolor={DIM}:x='{xpos}':y=(h-text_h)/2:alpha=0.3:enable='lt(t,{local_t})'"
        )
        filters.append(
            f"drawtext=fontfile={FONT_BOLD}:textfile='{tf}':fontsize=44:"
            f"fontcolor={WHITE}:x='{xpos}':y=(h-text_h)/2:alpha=1.0:enable='gte(t,{local_t})':"
            f"box=1:boxcolor=0xB0202A@0.0"
        )
    out = f"{SEGS}/seg_{i:02d}.mp4"
    if bg:
        cmd = ["ffmpeg","-y","-hide_banner","-loglevel","error","-loop","1","-i", IMG[bg],
               "-t", str(dur_render), "-vf", ",".join(filters), "-pix_fmt","yuv420p","-r",str(FPS), out]
    else:
        cmd = ["ffmpeg","-y","-hide_banner","-loglevel","error","-f","lavfi",
               "-i", f"color=c=black:s={W}x{H}:r={FPS}:d={dur_render}",
               "-vf", ",".join(filters), "-pix_fmt","yuv420p","-r",str(FPS), out]
    run(cmd)
    return out

