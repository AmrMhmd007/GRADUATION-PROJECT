def run(cmd):
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if r.returncode != 0:
        print("CMD FAILED:", " ".join(cmd))
        print(r.stdout.decode(errors="replace")[-4000:])
        sys.exit(1)

def txtfile(name, text):
    path = f"{TXT}/{name}.txt"
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return path

