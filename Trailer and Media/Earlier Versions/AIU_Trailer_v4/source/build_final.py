def caption_filters(cue, dur):
    """Render a list of (text,abs_start,abs_end) captions, fading in/out, never overlapping."""
    filters = []
    for ci, (text, a0, a1) in enumerate(cue.get("captions", [])):
        ls = a0 - cue["t0"]; le = a1 - cue["t0"]
        tf = txtfile(f"shot_{cue['_i']}_cap{ci}", text)
        alpha = (f"if(lt(t,{ls}),0,"
                 f"if(lt(t,{ls+0.3}),(t-{ls})/0.3,"
                 f"if(lt(t,{le-0.25}),1,"
                 f"if(lt(t,{le}),({le}-t)/0.25,0))))")
        enable = f"between(t,{ls},{le+0.05})"
        filters.append(
            f"drawtext=fontfile={FONT_BOLD}:textfile='{tf}':fontsize=42:fontcolor={WHITE}:"
            f"box=1:boxcolor=0x000000@0.42:boxborderw=20:"
            f"x=(w-text_w)/2:y=110:alpha='{alpha}':enable='{enable}'"
        )
    for si, (text, a0, a1) in enumerate(cue.get("subs", [])):
        ls = a0 - cue["t0"]; le = a1 - cue["t0"]
        tf = txtfile(f"shot_{cue['_i']}_sub{si}", text)
        alpha = (f"if(lt(t,{ls+0.3}),0,if(lt(t,{le}),1,0))")
        enable = f"between(t,{ls},{le+0.05})"
        filters.append(
            f"drawtext=fontfile={FONT_LIGHT}:textfile='{tf}':fontsize=20:fontcolor={DIM}:"
            f"x=(w-text_w)/2:y=h-80:alpha='{alpha}':enable='{enable}'"
        )
    return filters

def build_shot(i, cue, dur_render):
    dur = cue["t1"] - cue["t0"]
    img = IMG[cue["img"]]
    ken = cue.get("ken","in")
    tclamp = f"min(t\\,{dur})"
    if cue["img"] in SHORT_IMAGES:
        if ken == "zoom":
            base = [f"scale={W}:{H}:force_original_aspect_ratio=increase", f"crop={W}:{H}",
                    f"scale='iw*(1+0.06*{tclamp}/{dur})':-2:eval=frame",
                    f"crop={W}:{H}:'(iw-{W})/2':'(ih-{H})/2'"]
        else:
            base = [f"scale={W}:{H}:force_original_aspect_ratio=increase", f"crop={W}:{H}"]
    else:
        base = [f"scale={W}:-2"]
        if ken == "in":
            base.append(f"crop={W}:{H}:0:'min({tclamp}/{dur}*max(0\\,ih-{H})*0.4\\,max(0\\,ih-{H}))'")
        elif ken == "panfull":
            base.append(f"crop={W}:{H}:0:'min({tclamp}/{dur}*max(0\\,ih-{H})\\,max(0\\,ih-{H}))'")
        elif ken == "pan2":
            base.append(f"crop={W}:{H}:0:'max(0\\,ih-{H})*(0.35+0.20*min({tclamp}/{dur}\\,1))'")
        elif ken == "out":
            base.append(f"crop={W}:{H}:0:'max(0\\,ih-{H})*(1-min({tclamp}/{dur}\\,1))*0.3'")
        else:
            base.append(f"crop={W}:{H}:0:'max(0\\,ih-{H})*0.15'")
    filters = list(base)
    cue["_i"] = i
    filters += caption_filters(cue, dur)
    out = f"{SEGS}/seg_{i:02d}.mp4"
    cmd = ["ffmpeg","-y","-hide_banner","-loglevel","error","-loop","1","-i", img,
           "-t", str(dur_render), "-vf", ",".join(filters), "-pix_fmt","yuv420p","-r",str(FPS), out]
    run(cmd)
    return out

orig_dur = [round(c["t1"]-c["t0"], 6) for c in T]
seg_files = []
for i, cue in enumerate(T):
    dur_render = orig_dur[i] + (PAD if i < N-1 else 0.0)
    if cue["type"] == "black":
        f = build_black(i, cue, dur_render)
    elif cue["type"] == "cycle_precise":
        f = build_cycle_precise(i, cue, dur_render)
    elif cue["type"] == "clip":
        f = build_clip(i, cue, dur_render)
    elif cue["type"] == "reveal":
        f = build_reveal(i, cue, dur_render, final=False)
    elif cue["type"] == "final":
        f = build_reveal(i, cue, dur_render, final=True)
    elif cue["type"] == "shot":
        f = build_shot(i, cue, dur_render)
    seg_files.append(f)
    print(f"built segment {i}: {cue['type']} (orig {round(orig_dur[i],2)}s, rendered {round(dur_render,2)}s)")

# ---- Chain all segments with real crossfade dissolves (frame-padded so VO sync never drifts) ----
cum = []
running = 0.0
for d in orig_dur:
    running += d
    cum.append(running)

inputs = []
for sf in seg_files:
    inputs += ["-i", sf]

filter_parts = []
prev_label = "0:v"
for k in range(1, N):
    offset = cum[k-1] - orig_dur[0]*0 if k == 1 else cum[k-1]
    offset = cum[k-1]
    out_label = f"v{k}" if k < N-1 else "vout"
    filter_parts.append(
        f"[{prev_label}][{k}:v]xfade=transition=fade:duration={PAD}:offset={offset:.3f}[{out_label}]"
    )
    prev_label = out_label

filter_complex = ";".join(filter_parts)
video_out = f"{BUILD}/video_only3.mp4"
cmd = ["ffmpeg","-y","-hide_banner","-loglevel","error"] + inputs + [
    "-filter_complex", filter_complex, "-map","[vout]",
    "-c:v","libx264","-pix_fmt","yuv420p","-r",str(FPS),"-crf","18", video_out]
run(cmd)
print("VIDEO XFADE-CHAIN DONE:", video_out, "TOTAL:", TOTAL)
